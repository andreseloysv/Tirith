"""A lane worktree of a Node project gets node_modules linked from main, so the lane and its review can import."""

from __future__ import annotations

from pathlib import Path

from conftest import make_repo
from tirith import launch as launch_mod


def node_repo(path: Path, modules: bool = True) -> Path:
    path.mkdir(parents=True)
    (path / "package.json").write_text("{}\n")
    repo = make_repo(path)
    if modules:
        (repo / "node_modules" / "tweetnacl").mkdir(parents=True)
        (repo / "node_modules" / "tweetnacl" / "index.js").write_text("module.exports = {}\n")
    return repo


def test_worktree_node_modules_linked_to_main(tmp_path: Path) -> None:
    repo = node_repo(tmp_path / "app")
    tree = launch_mod.create_worktree(repo, "lane-a")
    link = tree / "node_modules"
    assert link.is_symlink()
    assert link.resolve() == (repo / "node_modules").resolve()
    assert (link / "tweetnacl" / "index.js").is_file()


def test_worktree_node_modules_link_excluded(tmp_path: Path) -> None:
    import subprocess
    repo = node_repo(tmp_path / "app3")
    (repo / ".gitignore").write_text("node_modules/\n")
    subprocess.run(["git", "-C", str(repo), "add", ".gitignore"], check=True)
    subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "ign"],
                   check=True)
    tree = launch_mod.create_worktree(repo, "lane-d")
    assert (tree / "node_modules").is_symlink()
    status = subprocess.run(["git", "-C", str(tree), "status", "--porcelain"], capture_output=True, text=True)
    assert status.stdout.strip() == ""


def test_worktree_node_modules_skipped_for_non_node_project(tmp_path: Path) -> None:
    repo = make_repo(tmp_path / "plain")
    (repo / "node_modules").mkdir()
    tree = launch_mod.create_worktree(repo, "lane-b")
    assert not (tree / "node_modules").exists()


def test_worktree_node_modules_skipped_when_main_has_none(tmp_path: Path) -> None:
    repo = node_repo(tmp_path / "app2", modules=False)
    tree = launch_mod.create_worktree(repo, "lane-c")
    assert not (tree / "node_modules").exists()


def test_review_links_without_repo(home: Path, tmp_path: Path) -> None:
    """A review given no repo finds the main checkout from the worktree and still links node_modules."""
    from conftest import write_config
    from tirith import review as review_mod
    from tirith.cli import end_lane, register_lane
    repo = node_repo(tmp_path / "nodeapp")
    (repo / "tirith.toml").write_text(
        'deploy = "none"\n[[pipelines]]\nid = "ci"\n[[pipelines.stages]]\nname = "test"\n'
        'run = "test -f node_modules/tweetnacl/index.js"\n', encoding="utf-8")
    import subprocess
    subprocess.run(["git", "-C", str(repo), "add", "tirith.toml"], check=True)
    subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "m"],
                   check=True)
    write_config(home, [{"id": "app", "name": "App", "repo": str(repo)}])
    tree = launch_mod.create_worktree(repo, "lane-n")
    (tree / "node_modules").unlink()  # a lane made before the link existed
    register_lane(home, lane_id="lane-n", project="app", hero_class="glasswright", feature="F",
                  workspace=str(tree), log=None, pid=None, brief=None)
    end_lane(home, "lane-n", "done", "built it")
    review = review_mod.review_lane(home, "lane-n", None, merge=False)
    assert (tree / "node_modules").is_symlink()
    assert review["status"] == "ready", review


def test_review_link_real_lane(home: Path, tmp_path: Path, monkeypatch) -> None:
    """The real lane: package.json and lockfile are right but main never installed, so the lane had no link.
    The review installs the dependencies in main once and links them into the worktree."""
    import json
    import os
    from conftest import write_config
    from tirith import review as review_mod
    from tirith.cli import end_lane, register_lane
    repo = tmp_path / "msgr"
    repo.mkdir()
    (repo / "package.json").write_text(json.dumps({"dependencies": {"tweetnacl": "^1.0.3"}}))
    (repo / "package-lock.json").write_text("{}\n")
    (repo / "tirith.toml").write_text(
        'deploy = "none"\n[[pipelines]]\nid = "ci"\n[[pipelines.stages]]\nname = "test"\n'
        'run = "test -f node_modules/tweetnacl/index.js"\n', encoding="utf-8")
    repo = make_repo(repo)
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    fake = bin_dir / "npm"  # stands in for the network install
    fake.write_text("#!/bin/sh\nmkdir -p node_modules/tweetnacl && echo 'module.exports={}' > node_modules/tweetnacl/index.js\n")
    fake.chmod(0o755)
    monkeypatch.setenv("PATH", f"{bin_dir}{os.pathsep}{os.environ['PATH']}")
    assert not (repo / "node_modules").exists()
    write_config(home, [{"id": "msgr", "name": "Msgr", "repo": str(repo)}])
    tree = launch_mod.create_worktree(repo, "lane-r")
    assert (tree / "node_modules").is_symlink()
    (tree / "node_modules").unlink()
    register_lane(home, lane_id="lane-r", project="msgr", hero_class="glasswright", feature="F",
                  workspace=str(tree), log=None, pid=None, brief=None)
    end_lane(home, "lane-r", "done", "built it")
    review = review_mod.review_lane(home, "lane-r", None, merge=False)
    assert (tree / "node_modules").is_symlink()
    assert review["status"] == "ready", review
