"""The hero face's body for the page: the app icon's star (app/src-tauri/icons/source/hero3d/mesh.glb) welded, centred
and scaled into the faces' frame, with where its painted eyes and mouth sit, written as
web/js/views/bots/face/hero-mesh.js. From the repo root: python3 tools/hero-face/make.py

The faces' frame (web/js/views/bots/face/geometry.js): a model unit is RMAX pixels of the 512-pixel mask that shows the
-25..125 box, so a box unit is 512/150 pixels; the box is the 2D face's (0..100, y down), where eyes and mouths are given.
"""
import base64
import os
import sys

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glb  # noqa: E402
import patch  # noqa: E402
import spots  # noqa: E402

GLB = 'app/src-tauri/icons/source/hero3d/mesh.glb'
OUT = 'web/js/views/bots/face/hero-mesh.js'
RMAX = 180.0  # its tips this far from its middle, in mask pixels: its body as big as the other faces look
PX = 512 / 150


def box(u, w):
    """A model point (u right, w up) in the box's units."""
    return (u * RMAX + 255.5) / PX - 25, (512 - (w * RMAX + 255.5)) / PX - 25


def outline(points, tris, n=360, size=512):
    """Its silhouette from the front as r(theta), theta from +u towards +w, the farthest reach 1."""
    pic = Image.new('L', (size, size))
    draw = ImageDraw.Draw(pic)
    at = lambda p: (size / 2 + p[0] * size * 0.47, size / 2 - p[1] * size * 0.47)  # noqa: E731
    for t in tris:
        draw.polygon([at(points[i]) for i in t], fill=255)
    mask = np.asarray(pic) > 0
    r = np.zeros(n)
    for k in range(n):
        th = 2 * np.pi * k / n
        for d in np.arange(size / 2 - 1, 0, -0.5):
            x, y = int(size / 2 + d * np.cos(th)), int(size / 2 - d * np.sin(th))
            if mask[y, x]:
                r[k] = d / (size * 0.47)
                break
    return r / r.max()


def b64(a):
    return base64.b64encode(a.tobytes()).decode()


def main():
    points, uv, tris, picture = glb.read(GLB)
    eyes, mouth = spots.features(points, uv, tris, picture)
    pts, inverse = np.unique(np.round(points, 5), axis=0, return_inverse=True)
    tris = inverse.reshape(-1)[tris]
    domes = [(mouth[0], max(mouth[1], 0.07), max(mouth[2], 0.07))] + eyes  # the mouth's bump is wider than its paint
    pts, tris = patch.patch(pts, tris, domes, cut=1.5)
    middle = (pts.min(0) + pts.max(0)) / 2
    scale = np.hypot(pts[:, 0] - middle[0], pts[:, 1] - middle[1]).max()
    pts = (pts - middle) / scale
    at = [(m - middle) / scale for m, _, _ in eyes + [mouth]]
    unit = RMAX / PX / scale  # a mesh length in box units
    (lx, ly), (rx, ry), (mx, my) = (box(p[0], p[1]) for p in at)
    eye = [lx, rx, (ly + ry) / 2, (eyes[0][1] + eyes[1][1]) / 2 * unit, (eyes[0][2] + eyes[1][2]) / 2 * unit]
    eye = [round(float(v), 1) for v in eye]
    o = [round(float(v), 1) for v in (mx, my, mouth[1] * unit, mouth[2] * unit)]
    s = float(np.abs(pts).max())
    q = np.round(pts / s * 32767).astype('<i2')
    r = ','.join(f'{x:.4f}'.rstrip('0').rstrip('.') for x in outline(pts, tris))
    with open(OUT, 'w') as f:
        f.write('// The hero face\'s body: the app icon\'s star (app/src-tauri/icons/source/hero3d/mesh.glb) welded, centred and\n'
                '// scaled into the faces\' frame, with its painted eyes and mouth. Generated by tools/hero-face/make.py: do not edit.\n')
        f.write(f"export const HERO_MESH = {{ rmax: {RMAX}, s: {s:.6f}, eyes: {eye}, o: {o}, r: [{r}],\n"
                f"  pos: '{b64(q)}',\n  idx: '{b64(tris.astype('<u2'))}' }};\n")
    print(f'{OUT}: {len(pts)} points, {len(tris)} triangles, eyes {eye}, mouth {o}')


if __name__ == '__main__':
    main()
